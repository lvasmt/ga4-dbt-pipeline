{{ config(materialized='view') }}

with aggregated as (

    select
        coalesce(user_id, user_pseudo_id, concat('anonymous-', cast(stream_id as string))) || '-' || cast(ga_session_id as string) as session_code, -- fallback for consent-denied hits where both identifiers are null; ga_session_id still varies per anonymous visit so this keeps them distinguishable instead of colliding
        user_pseudo_id,
        user_id,
        stream_id,
        ga_session_number,
        session_source,
        session_medium,
        session_campaign_name,
        device_category,
        device_brand,
        device_model,
        device_marketing_name,
        min(event_timestamp) as session_start_timestamp,
        min(event_date) as session_date,
        array_agg(struct(page_location, page_title) order by event_timestamp limit 1)[offset(0)] as landing_event,
        min(country) as country, -- geo is IP-derived per hit, not documented as fixed per session like traffic source is -- MIN() kept defensively in case it genuinely varies mid-session
        min(city) as city,
        sum(engagement_time_msec) as total_engagement_time_msec,
        max(session_engaged) = 1 as is_engaged_session,
        min(event_timestamp) = min(user_first_touch_timestamp) as is_new_user -- device-level only; not accurate once user_id is configured across devices
    from {{ ref('int_consented_events') }}
    group by
        user_pseudo_id,
        user_id,
        stream_id,
        ga_session_id,
        ga_session_number, -- constant per session (GA4-generated sequence number), safe to group by directly
        session_source, -- session_traffic_source_last_click is fixed at session start by GA4 itself -- safe to group by directly, not an aggregation pick
        session_medium,
        session_campaign_name,
        device_category, -- a GA4 session is generated by one SDK instance on one device, can't span two devices -- safe to group by directly
        device_brand,
        device_model,
        device_marketing_name

)

select
    session_code,
    user_pseudo_id,
    user_id,
    ga_session_number,
    session_start_timestamp,
    session_date,
    split(landing_event.page_location, '?')[offset(0)] as landing_page_path,
    landing_event.page_title as landing_page_title,
    session_source,
    session_medium,
    session_campaign_name,
    device_category,
    device_brand,
    device_model,
    device_marketing_name,
    country,
    city,
    total_engagement_time_msec,
    is_engaged_session,
    is_new_user
from aggregated
